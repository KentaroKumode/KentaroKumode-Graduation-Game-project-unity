namespace MetaProgression
{
    /// <summary>
    /// 挑戦モード用の段階デバフ。Lv1 〜 Lv10 を独立トグルで重複適用可能。
    /// 全 ON でバフトラック満開放が最低クリア条件、というバランスを想定。
    /// </summary>
    public enum MetaDebuffLevel
    {
        Lv1_困窮した商隊 = 1,        // ショップ価格 +25%
        Lv2_俊敏 = 2,                // 敵が各戦闘の最初の1回の被弾を必ず回避する
        Lv3_向かい風 = 3,            // 敵への与ダメ -1
        Lv4_前途多難 = 4,            // マップ視界 2マスで遮断
        Lv5_偽の商人 = 5,            // ショップマスが30%で偽商人化。踏むと特殊エリート戦(3T後に逃走=恒久アイテム1喪失/勝利=レア恒久アイテム1獲得)
        Lv6_死神の影 = 6,            // 3層突入時に固有恒久デバフ +1
        Lv7_補給断絶 = 7,            // 前哨基地の回復上限 = 最大HPの50%
        Lv8_飢餓の極地 = 8,          // ハンガー初期値 -2/フロア
        Lv9_鋼の皮膚 = 9,            // 敵が初回致命傷をHP1で耐える
        Lv10_天変地異 = 10,          // 全戦闘で敵ダメ+100% / 1層突入時に恒久デバフ +1 / ラストスタンドが発動しなくなる
    }
}
