namespace MetaProgression
{
    /// <summary>
    /// 挑戦デバフの軸。 正本: docs/GAME.md §15-2（**v4.0**）。
    ///
    /// **v4.0 (2026-08-10)**: v3.0 の「全 10 軸を T1/T2/T3 で揃える」を破棄した。
    ///
    /// 揃えたことで UI と説明は簡単になったが、 **段数を効果に合わせるのではなく
    /// 効果を段数に合わせて刻む**ことになり、 T1→T3 の差が 5% 前後まで潰れていた。
    /// 難易度の梯子を伸ばすために乗算デバフを緩めた結果、 潰れが決定的になった。
    ///
    /// v4.0 の構成:
    ///   - **段数は効果の性質が決める。** 伸ばして意味がある効果だけ多段にする (1〜3 段)
    ///   - **点数は段番号と切り離す。** 1 段目が 2pt の軸があってよい
    ///   - **基礎軸の最上位は 3pt まで。** 4pt は Tier4 の専用値 (読み違えを防ぐ)
    ///   - **1 カテゴリの最大は 6pt** で不変。 軸数はカテゴリごとに違ってよい (2〜3 軸)
    ///   - 5 カテゴリ × 6pt = 基礎 30pt、 + Tier4 5 種 × 4pt = **全盛り 50pt**
    ///
    /// **1 軸で選べる Tier は 1 つ**。 高 Tier は低 Tier を内包する。
    /// **軸の合計点 = その軸の最上位 Tier の点数**（段を足し上げない）。
    ///
    /// 効果値はここに書かない（<see cref="MetaDebuffApplicator"/> が唯一の正本）。
    /// </summary>
    public enum ChallengeAxis
    {
        // ---------- A. 生存圧 (6pt) ----------
        /// <summary>3段 1/2/3pt — ラン累計被ダメの 4% / 8% / 12% だけ最大HPを恒久減少（上限20）</summary>
        長引く負傷   = 1,
        /// <summary>2段 1/2pt — 消耗品の同時所持上限 3/2 個</summary>
        穴の空いた鞄 = 2,
        /// <summary>1段 1pt — すべての回復量 ×0.80</summary>
        遅い回復     = 11,   // 旧〈浅い眠り〉。 序数は変えない

        // ---------- B. 敵強化 (6pt) ----------
        /// <summary>2段 2/3pt — 敵HP ×1.25 / ×1.50</summary>
        厚い皮膚     = 3,
        /// <summary>3段 1/2/3pt — 敵ダメージ ×1.05 / ×1.10 / ×1.20</summary>
        狂暴化       = 4,

        // ---------- C. 戦闘則 (6pt) ----------
        /// <summary>2段 2/3pt — 同時に配線できる端子の上限 3 / 2</summary>
        綻び         = 5,   // 旧〈不器用〉。 序数は変えない
        /// <summary>2段 1/3pt — ダイス1本が1固定 (最初の2T / 5T)。リロールで戻せる</summary>
        見放された運 = 6,

        // ---------- D. 経済 (6pt) ----------
        /// <summary>2段 2/3pt — ショップ価格 ×1.10 / ×1.15</summary>
        搾取経済     = 7,
        /// <summary>1段 1pt — 層移動時に所持GOLDの10%を失う</summary>
        通行料       = 12,   // 旧〈売り渋り〉(陳列削減+値上げ)。 序数は変えない
        /// <summary>1段 2pt — 前哨基地で休憩するたび GOLD −5</summary>
        宿屋連合     = 13,

        // ---------- E. 崩壊 (6pt) ----------
        /// <summary>3段 1/2/3pt — 希望上限 −5 / −10 / −15</summary>
        絶望的な戦闘 = 9,
        /// <summary>1段 3pt — エスカレーション閾値を 2T 前倒し</summary>
        天変地異     = 10,

        // ---------- v4.0 で廃止 (enum 値は再利用しない) ----------
        // 8  = 補給断絶 → 〈浅い眠り〉へ縮小
        // 14 = 俊敏     → 廃止 (会心率減は天井を削るだけで技量で答えられない)
        // 練度不足(2) は〈穴の空いた鞄〉へ差し替え済み、 脆弱な肉体(1) は〈長引く負傷〉へ改名
    }

    /// <summary>
    /// カテゴリ Tier4（各 4pt・合計 20pt）。
    ///
    /// **解禁ゲートであって自動引き上げではない。**
    /// v4.0 で条件を「同カテゴリの 2 軸がどちらも T3」から
    /// **「同カテゴリの基礎軸で 6pt 払っている」**へ変えた ── 段数が軸ごとに違うので、
    /// Tier 番号で条件を書けなくなったため。 払う額は同じ 6pt で厳しさは変わらない。
    ///
    /// Tier4 は数値をさらに刻むのでなく、**巨大だが一目で数えられる規則**を追加する。
    /// </summary>
    public enum ChallengeT4
    {
        /// <summary>A: 各層最初の戦闘で HP を最大HPの 86% 以下へ切り詰め / 全回復 ×0.92</summary>
        破綻       = 1,
        /// <summary>B: 各戦闘 1 回、 敵が致命傷を HP1 で耐える</summary>
        鋼の皮膚   = 2,
        /// <summary>C: 全16役からランダムに2役をラン中封印</summary>
        凶運       = 3,
        /// <summary>D: 開幕 GOLD −10 / 売却額 −20%</summary>
        破産       = 4,
        /// <summary>E: ラン累計125戦闘ターン以降、すべての被ダメージ×1.30</summary>
        最後の審判 = 5,
    }

    /// <summary>軸のカテゴリ。 各カテゴリ最大 6pt + Tier4 4pt。</summary>
    public enum ChallengeCategory
    {
        A生存圧 = 0,
        B敵強化 = 1,
        C戦闘則 = 2,
        D経済   = 3,
        E崩壊   = 4,
    }
}
