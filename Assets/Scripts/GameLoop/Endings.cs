namespace GameLoop
{
    /// <summary>
    /// ラン・クリア時のエンディング。「最後に撃破したボス(lastBossId)」＋（覚者のみ gedatsuVictory）で分岐する。
    /// - boss_layer5      審判官 → end1 英雄の帰還
    /// - boss_layer5_hidden 剣聖 → end2 無明の剣
    /// - boss_layer6      灰燼の王 → end3 空の玉座
    /// - boss_layer7      覚者(通常) → end4 最後の見出し ／ 覚者(解脱) → end5 シグナル・リターン
    /// 表示は当面ログのみ（GameManager の RunClear 地点で出力）。
    /// </summary>
    public static class Endings
    {
        public struct Ending
        {
            public string id;
            public string title;
            public string body;
            public string Display => $"=== ENDING: {title} ===\n{body}";
        }

        public static Ending Resolve(RunState run)
        {
            string b = run?.lastBossId ?? "";
            switch (b)
            {
                case "boss_layer7":        return (run != null && run.gedatsuVictory) ? End5 : End4;
                case "boss_layer6":        return End3;
                case "boss_layer5_hidden": return End2;
                case "boss_layer5":        return End1;
                default:                   return End1; // 想定外はとりあえず帰還エンド
            }
        }

        public static readonly Ending End1 = new Ending
        {
            id = "end1", title = "英雄の帰還",
            body =
                "あなたはついに未踏の地からの帰還を成し遂げた。\n" +
                "深層から得られた遺物、情報、安全なルート、それらに対してギルドから支払われた報奨金は、一生遊んで暮らせるほどの額だった。あなたはしばらくの間、友人や家族とともに平穏で満ち足りた日々を過ごした。\n" +
                "しかし、あなたがあの大穴を忘れることはなかった。\n" +
                "あの旅で、あなたは何を得て、何を失ったのだろうか。",
        };

        public static readonly Ending End2 = new Ending
        {
            id = "end2", title = "無明の剣",
            body =
                "あなたはついに剣聖の刃を打ち破った。\n" +
                "彼の剣は激しく、そして静かに勝利を渇望していた。最後の一滴まで血を絞り尽くし、剣聖が膝をついたその時、その剣もまた朽ちるように消えていった。\n" +
                "街へ帰還したあなたは、この体験を誰にも語らなかった。\n" +
                "やがて剣を携え、ひとり街を後にする。\n" +
                "その行方を知る者は、誰もいない。",
        };

        public static readonly Ending End3 = new Ending
        {
            id = "end3", title = "空の玉座",
            // 6F王継承＝当該 iteration 内の局所的延命に過ぎない、という諦観のトーン。
            // 7F覚者撃破（End4/End5）との対比＝「向こう側へ降りる」を含意で置く。
            body =
                "玉座は空になった。\n" +
                "滅びを見届け続けた王は去り、\n" +
                "玉座は、次の堰を待っていた。\n" +
                "\n" +
                "あなたは玉座に着く。\n" +
                "座した瞬間、奇妙な既視感が降りてくる。\n" +
                "皆と同じく、「自分が座るべき席だった」と思った。\n" +
                "皆、座った後で知った——もう帰る道は無いと。\n" +
                "\n" +
                "楔は、また少しだけ抜けた。\n" +
                "遺物の産出は、また少しだけ増えるだろう。\n" +
                "街は、また少しだけ栄えるだろう。\n" +
                "\n" +
                "あなたは空の玉座に着き、そしてついに帰ることはなかった。",
        };

        public static readonly Ending End4 = new Ending
        {
            id = "end4", title = "最後の見出し",
            // 覚者を撃破＝主人公が次の覚者になる。
            // 前半：街の50年没落を新聞見出しで綴る（局所現象＝iteration 内の終わり）。
            // 後半：覚者となった主人公が、宇宙崩壊・新宇宙誕生・次の主人公到来までを見届ける長大な時。
            // 末尾：覚者の問いで開く（次反復の主人公への、心の底からの希望を込めた問い）。
            body =
                "街は地図から消えた。\n" +
                "あなたはそれを、向こう側から見届けていた。\n" +
                "\n" +
                "大穴の拡大は、止まらなかった。\n" +
                "通りを、家を、街を、山を、海を。\n" +
                "やがて星も、月も、太陽も。\n" +
                "銀河すらも、ゆっくりと歪み、引き込まれていった。\n" +
                "あなたは絶望のなかにあった。あの頃はまだ、家族の顔も、街の細部も、覚えていた。\n" +
                "\n" +
                "無限に近しい時の流れの果てに、辺りが闇に包まれた。\n" +
                "すべてを呑み込んだ大穴は、ただ一つの黒点へと収束し、刹那の後、弾けた。\n" +
                "\n" +
                "新たな宇宙が冷えていく時。星が生まれる時。惑星が固まる時。生命が芽吹く時。\n" +
                "あなたはそれを、ただ見ていた。\n" +
                "最初の数億年には、まだ感情らしきものが残っていた。\n" +
                "次の数億年で、それすらも擦り切れた。\n" +
                "\n" +
                "やがて、星のひとつに、覚えのある形をした街が立ち上がった。\n" +
                "\n" +
                "覚えのある母が、覚えのある半熟卵を作っていた。\n" +
                "覚えのある男が、浅い層で日銭を拾っていた。\n" +
                "覚えのある祖父母が、立て続けに逝った。\n" +
                "覚えのある男が、いつもの引き返し地点を、一歩、越えた。\n" +
                "\n" +
                "あなたは待った。\n" +
                "彼が確信を育て、層を抜け、ここまで辿り着くまでを。\n" +
                "\n" +
                "そして、あなたは問うた。\n" +
                "\n" +
                "「——何を求めて、ここまで来た。」",
        };

        public static readonly Ending End5 = new Ending
        {
            id = "end5", title = "シグナル・リターン",
            // 無上正等覚を撃破＝宇宙の決定論的ループが崩壊。
            // 朝のキッチンの "ほんの少しのズレ"（半熟卵→堅焼き卵）だけで、世界全体の質的転換を示唆。
            // 由来：オープニングで「お父さんが半熟好きだったから」という由来を仕込んでおく。
            // 決定論崩壊後はその因果連鎖が再現されず、母は堅焼きを焼く世界になる。
            // 目覚めた "あなた" が同一人物かは敢えて不確定。プレイヤーの読みに委ねる。
            body =
                "目を覚ますと、朝だった。\n" +
                "\n" +
                "階下から、いつもの匂いが上がってくる。\n" +
                "\n" +
                "身を起こす。枕元の壁には、父の写真が掛けてある。\n" +
                "\n" +
                "階段を下りる。食卓の前で、母さんが振り返って、おはよう、と言った。\n" +
                "皿に並んでいるのは、堅焼き卵、ベーコン、堅焼きパン。\n" +
                "\n" +
                "上の妹が、まだ眠そうな顔で食卓につく。\n" +
                "下の妹は、もう先に出かけたあとだった。\n" +
                "\n" +
                "「いってきます」 とあなたは言った。\n" +
                "「気をつけて」 と母さんは応えた。\n" +
                "\n" +
                "母さんが 「気をつけて」 と言うのは、もう数千回目だった。\n" +
                "\n" +
                "外に出ると、大穴のほうから、朝靄が這い上がってくるのが見えた。\n" +
                "緑の札を懐に入れ、いつものように、その縁まで歩く。",
        };
    }
}
