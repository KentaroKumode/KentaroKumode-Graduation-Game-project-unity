    /// <summary>
    /// ラン終了時のエンディング。「最後に撃破したボス(lastBossId)」で分岐する。
    /// - boss_layer5      審判官 → end1 英雄の帰還
    /// - boss_layer5_hidden 剣聖 → end2 無明の剣
    /// - boss_layer6      灰燼の王 → end3 空の玉座
    /// - boss_layer7      ヴェスカ撃破 → **撃破後の一択で分岐** (RunState.riftLeftOpen)
    ///                      false = EndTrue〈裂け目を閉じる〉 / true = EndGood〈閉じない〉
    /// - ヴェスカに敗北   → **エンディング無し** (2026-08-17。 End4 は定義のみ残置)
    ///
    /// 2026-07-27 リワーク: 旧「解脱」特殊勝利の分岐を廃止。
    /// End4 は **敗北して向こう側に残される** エンドに、
    /// End5 は「決定論が崩壊する」ではなく **裂け目を塞ぐ** エンドになった。
    /// 3 つの姿勢: End1/End2 = 帰る ／ End3・End4 = 留まる ／ EndTrue = 塞ぐ。正本: docs/GAME.md §20。
    ///
    /// 2026-08-17 リワーク: **エンディングをヴェスカ撃破後の一択だけに集約した。**
    ///   敗北のたびに同じ文章を読ませるのは物語ではなく作業になるため、 End4 の自動表示を止めた。
    ///   旧 End5 (勝利・無条件) は代償が軽すぎた ── 主人公が生きて登り、 母は同じ台所に立っていた。
    ///   **主人公自身を収支に含める** EndTrue と、 **閉じないことを選ぶ** EndGood に割った。
    ///
    /// 額縁 (2026-07-21):
    ///   本作『DICE BOUND』は、EndTrue の後に七層で見つかった手記から起こされた古典『大穴』(著者不明・帝都刊)
    ///   の卓上遊戯翻案、という体裁を取る。刊行社は国家間戦争で焼失し、原著は口伝と劇団台本の断片からのみ復元される。
    ///   EndTrue 到達で Epilogue が unlock され、「刊行史 + 焼け残った あとがき」がプレイヤーに開示される。
    ///   **EndGood では本が書かれない**ので額縁は閉じない ── 接続しないことが GOOD END の代償にあたる。
    ///
    /// 表示は当面ログのみ（GameManager の RunClear 地点で出力）。
    /// </summary>
    public static class Endings
    {
        public struct Ending
        {
            public string id;
            public string title;
            public string body;
            public string Display => $"=== ENDING: {title} ===\n{body}";
        }

        public static Ending Resolve(RunState run)
        {
            // **敗北ではエンディングを出さない (2026-08-17)。**
            //   死ぬたびに同じ文章を読ませるのは、 物語ではなく作業になる。
            //   End4 は定義だけ残してあるが、 どこからも参照していない (下の doc 参照)。

            string b = run?.lastBossId ?? "";
            switch (b)
            {
                // ヴェスカ撃破後の一択で分岐する。 これが唯一のエンディング分岐。
                case "boss_layer7":        return run != null && run.riftLeftOpen ? EndGood : EndTrue;
                case "boss_layer6":        return End3;
                case "boss_layer5_hidden": return End2;
                case "boss_layer5":        return End1;
                default:                   return End1; // 想定外はとりあえず帰還エンド
            }
        }

