namespace GameLoop
{
    /// <summary>戦闘勝利報酬の配分。 <b>「現物で払うか、金で払うか」の比率をここ 1 箇所で持つ。</b>
    ///
    /// <para><b>なぜ 1 箇所に集めるか。</b> ドロップ率は <c>GameManager</c> の戦闘終了処理に、
    /// ゴールドは <c>FloorManager.CalculateRewardCoins</c> に、 と離れて置かれていた。
    /// この 2 つは<b>足して 1 つの報酬</b>なので、 片方だけ動かすと供給量が静かにずれる。
    /// 実際 2026-09-09 に通常戦のドロップを 50% → 15% へ落としたとき、
    /// 補償のゴールド増 (×3 → ×4) は別ファイルで別途決めており、
    /// 「意図的に過少補償」という判断がコードから読めなくなっていた。</para>
    ///
    /// <para><b>2026-09-15 の方針転換: ランダムドロップより<u>店での購入</u>に重みを置く。</b>
    /// 直前の実測 (Balanced 10,000 ラン) では 1 ラン のパッシブ取得 32.32 品の内訳が
    /// ショップ 11.45 (35.4%) / 戦闘報酬 9.39 (29.0%) / Λ 3.52 / イベント 2.22 /
    /// 交換 2.08 / 開幕 2.00 / 宝箱 1.67 で、 <b>無料経路が 45.1%</b> を占めていた。
    /// 一方ショップは 1 ラン 52.87 枠も陳列されているのに購入は 11.45 品 (成約 21.7%) ──
    /// <b>棚が足りないのではなく金が足りない</b>。 供給を店へ寄せるには
    /// 「無料の現物を削り、 その価値を金にして返す」しかない。</para>
    ///
    /// <para><b>エリートの確定ドロップを外した理由。</b> 2026-09-09 にエリートを
    /// 「期待値そのまま・分散ゼロ」(0.5+0.5 → 確定 1.0) にしたが、 通常戦だけを
    /// 0.5 → 0.15 へ絞った結果、 <b>期待値の比が 2 倍から 6.7 倍へ開いた</b>。
    /// これがエリートを「踏むほど得」にしていた主因で (ゴールド倍率を ×1.3〜×1.8 で
    /// 振っても傾きは 2〜3pt しか動かなかった)、 確定を外すと
    /// <b>供給を店へ寄せる目的とエリートの損得の是正が同時に進む</b>。</para></summary>
    public static class CombatRewards
    {
        /// <summary>エリート戦の勝利で恒久パッシブが落ちる確率。
        /// <b>2026-09-15: 確定 1.0 → 0.40。</b></summary>
        public static float EliteDropRate = 0.40f;

        /// <summary>通常戦の勝利で恒久パッシブが落ちる確率。
        /// 0.50 (〜2026-09-09) → 0.15 → <b>0.10 (2026-09-15)</b>。</summary>
        public static float NormalDropRate = 0.10f;

        /// <summary>戦闘報酬ゴールドの倍率。 <c>FloorManager.CalculateRewardCoins</c> の
        /// <c>(7 + floor/2)/5</c> に掛かる整数係数。 ×3 (2026-08-10) → ×4 (2026-09-09) →
        /// <b>×5 (2026-09-15)</b> ── 削った現物を金で返すぶん。
        ///
        /// <para><b>一度 ×6 で測って戻した。</b> 実測 (10,000 ラン) でショップ比は 35.7% → 46.9% と
        /// 目的を達したが、 <b>補償が過剰</b>だった: 獲得ゴールドが 312 → 524G (×1.68)、
        /// 総供給が 32.01 → 34.69 品、 クリア率が +9.12pt 振れた (判定基準は ±2pt)。
        /// 余った金は棚ではなく<b>リロールへ溶けた</b> (5.56 → 10.54 回 / 86G → 188G) ──
        /// 「選択に重みを置く」意図とは違う使われ方。 削った現物は 3.5 品ぶんなので ×5 が上限。</para>
        ///
        /// <para><b>倍率ではなく実数値。</b> 較正で倍率を振ったあとは必ずこの既定値へ畳むこと
        /// (CLAUDE.md「隠し倍率禁止・実数値を直接調整」)。</para></summary>
        public static int GoldScale = 5;

        /// <summary>エリート戦の報酬ゴールド倍率。
        /// 1.8 → 2.6 (2026-09-15) → <b>2.0 (2026-09-20)</b>。 航行がエリートの戦闘コストを見積もるようになり、
        /// 稼ぎがエリートに偏りすぎていたため。 <b>航行スコアもこの値を読む</b> (<c>AutoRunner.Rank</c> の goldPull)。</summary>
        public static float EliteRewardMul = 2.0f;
        public const float EliteRewardMulDefault = 2.0f;

        /// <summary>[計装] 落ちた回数 / 抽選した回数。 エリートと通常を分けて数える
        /// ── 合算だと「どちらの経路が供給しているか」が読めない。</summary>
        public static long EliteRolls, EliteDrops, NormalRolls, NormalDrops;

        public static void ResetStats()
        { EliteRolls = EliteDrops = NormalRolls = NormalDrops = 0; }
    }
}
