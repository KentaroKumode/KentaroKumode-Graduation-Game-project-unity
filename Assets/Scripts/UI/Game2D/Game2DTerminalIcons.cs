    /// 様式 (2026-11-11): 明るい主役 + その後ろに敷く暗めの飾り (輪・枠・筋) の 2 色だけ。 主役の中の線は抜き (本体の色) で表す。
    /// 物の絵に限らず、 意味を表す記号でよい。 奇数の寸法なので中央の列・行が取れる。
    /// 表は 1 行 17 文字 × 17 行: '.' = 透明 / '2' = 後ろの飾り / '3' = 主役。
    /// 確認用の一覧画像は Tools/terminal_icons_preview.py で書き出す。
    /// </summary>
    public static class Game2DTerminalIcons
    {
        public const int Size = 17;
        /// <summary>値: 後ろの飾り / 主役。 0 = 透明。</summary>
        public const byte Back = 2, Front = 3;

        static Dictionary<string, byte[]> _cache;

        /// <summary>長さ Size × Size (行優先・左上から)・値 0 / Back / Front。 無ければ null。</summary>
        public static byte[] Get(string id)
        {
            if (string.IsNullOrEmpty(id)) return null;
            if (_cache == null) Build();
            return _cache.TryGetValue(id, out var px) ? px : null;
        }

        static void Build()
        {
            _cache = new Dictionary<string, byte[]>();
            foreach (var kv in Table())
            {
                var rows = kv.Value;
                if (rows.Length != Size) continue;
                var px = new byte[Size * Size];
                bool ok = true;
                for (int y = 0; y < Size && ok; y++)
                {
                    var r = rows[y];
                    if (r.Length != Size) { ok = false; break; }
                    for (int x = 0; x < Size; x++)
                    {
                        char c = r[x];
                        px[y * Size + x] = c == '3' ? Front : c == '2' ? Back : (byte)0;
                    }
                }
                if (ok) _cache[kv.Key] = px;
            }
        }

