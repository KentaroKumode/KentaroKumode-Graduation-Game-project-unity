        public const int Size = 16;

        static Dictionary<string, byte[]> _cache;

        /// <summary>長さ 256 (行優先・左上から)・値 0〜3。 無ければ null。</summary>
        public static byte[] Get(string id)
        {
            if (string.IsNullOrEmpty(id)) return null;
            if (_cache == null) Build();
            return _cache.TryGetValue(id, out var px) ? px : null;
        }

        static void Build()
        {
            _cache = new Dictionary<string, byte[]>();
            foreach (var kv in Table())
            {
                var rows = kv.Value;
                if (rows.Length != Size) continue;
                var px = new byte[Size * Size];
                bool ok = true;
                for (int y = 0; y < Size && ok; y++)
                {
                    var r = rows[y];
                    if (r.Length != Size) { ok = false; break; }
                    for (int x = 0; x < Size; x++)
                    {
                        char c = r[x];
                        px[y * Size + x] = (byte)(c >= '1' && c <= '3' ? c - '0' : 0);
                    }
                }
                if (ok) _cache[kv.Key] = px;
            }
        }

