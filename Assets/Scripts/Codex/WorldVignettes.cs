        public static IReadOnlyList<Vignette> All => _all;

        private static readonly Dictionary<string, Vignette> _byId = BuildIndex();

        private static Dictionary<string, Vignette> BuildIndex()
        {
            var d = new Dictionary<string, Vignette>(_all.Count);
            foreach (var v in _all)
                d[v.id] = v;
            return d;
        }

        /// <summary>id 文字列（enum name）で検索。見つからなければ null。</summary>
        public static Vignette GetById(string id)
        {
            if (id == null) return null;
            _byId.TryGetValue(id, out var v);
            return v;
        }
