# BudouX ja モデル (v0.7.0・Apache 2.0・https://raw.githubusercontent.com/google/budoux/v0.7.0/budoux/models/ja.json) を C# の表に変換する。
# 使い方: python Tools/jp_linebreak/gen_model.py ja.json Assets/Scripts/UI/Game2D/JpBreakModel.cs
import json, sys
m = json.load(open(sys.argv[1], encoding='utf-8'))
def esc(s): return ''.join(chr(92) + 'u%04x' % ord(c) for c in s)
out = []
out.append('// <auto-generated> BudouX (https://github.com/google/budoux) v0.7.0 の日本語モデル budoux/models/ja.json を表にしたもの。')
out.append('// Copyright Google LLC・Apache License 2.0 (THIRD_PARTY_NOTICES.md)。 生成: Tools/jp_linebreak/gen_model.py (手で直さない)。')
out.append('namespace UI.Game2D')
out.append('{')
out.append('    internal static class JpBreakModel')
out.append('    {')
total = sum(sum(g.values()) for g in m.values())
out.append('        /// <summary>BudouX の base_score の 2 倍 (= -全特徴の重みの和)。 整数で持つため、 比較は 2*score で行う。</summary>')
out.append('        internal const int BaseScore2 = %d;' % (-total))
for k in ['UW1','UW2','UW3','UW4','UW5','UW6','BW1','BW2','BW3','TW1','TW2','TW3','TW4']:
    g = m.get(k, {})
    keys = '"' + ''.join(esc(x) for x in g.keys()) + '"'
    vals = ', '.join(str(v) for v in g.values())
    out.append('        internal const string %sKeys = %s;' % (k, keys))
    out.append('        internal static readonly int[] %sVals = { %s };' % (k, vals))
out.append('    }')
out.append('}')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('total', total)
