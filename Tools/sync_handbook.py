"""docs/handbook.md (手引きの正本) から、 画面に出す手引きの文 (C#) を作る。

    python Tools/sync_handbook.py            # Assets/Scripts/UI/Game2D/Screens/Game2DTutorialText.cs を書き直す
    python Tools/sync_handbook.py --check    # 書き直さずに、 生成物が handbook と一致しているかだけ見る (違えば終了コード 1)
    python Tools/sync_handbook.py --plain F  # 画面に出す字だけを F へ書く (python Tools/glyph_check.py F で字の有無を調べる)

handbook を直したら、 これを回してから Unity に戻る。 生成物は手で直さない。
読み方: 「## 見出し」の次の行が「*— 出す契機*」の節だけを拾う (目次・See Also は契機の行が無いので拾わない)。
本文は空行で段落に分け、 段落の中の改行はつなぐ。 太字 (**…**) は記号のまま残す ── 画面が強調の色で描く。
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "handbook.md")
OUT = os.path.join(ROOT, "Assets", "Scripts", "UI", "Game2D", "Screens", "Game2DTutorialText.cs")

TRIGGER = re.compile(r"^\*—\s*(.+?)\s*\*$")


def parse(text):
    """[(見出し, 契機, [段落...])] を返す。"""
    lines = text.splitlines()
    out, i = [], 0
    while i < len(lines):
        m = re.match(r"^## (.+?)\s*$", lines[i])
        if not m:
            i += 1; continue
        title = m.group(1)
        j = i + 1
        while j < len(lines) and not lines[j].strip(): j += 1
        tm = TRIGGER.match(lines[j].strip()) if j < len(lines) else None
        if not tm:
            i += 1; continue
        trigger = tm.group(1)
        paras, cur = [], []
        k = j + 1
        while k < len(lines):
            s = lines[k].strip()
            if s.startswith("#") or s == "---": break
            if not s:
                if cur: paras.append("".join(cur)); cur = []
            else:
                cur.append(s)
            k += 1
        if cur: paras.append("".join(cur))
        out.append((title, trigger, paras))
        i = k
    return out


def cs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render(sections):
    w = io.StringIO()
    w.write("// <auto-generated>\n")
    w.write("// Tools/sync_handbook.py が docs/handbook.md から作る。 手で直さない ── handbook を直して回し直す。\n")
    w.write("// </auto-generated>\n")
    w.write("namespace UI.Game2D\n{\n")
    w.write("    public static partial class Game2DTutorialText\n    {\n")
    w.write("        /// <summary>handbook の節 (見出し・出す契機・本文)。 本文の段落は \\n で区切る。 **…** は強調。</summary>\n")
    w.write("        public static readonly Entry[] All =\n        {\n")
    for title, trigger, paras in sections:
        w.write("            new Entry(%s, %s,\n                %s),\n" % (cs_str(title), cs_str(trigger), cs_str("\n".join(paras))))
    w.write("        };\n    }\n}\n")
    return w.getvalue()


def main():
    args = sys.argv[1:]
    sections = parse(io.open(SRC, encoding="utf-8-sig").read())
    body = render(sections)
    if args and args[0] == "--plain":
        plain = "\n".join(t + "\n" + "\n".join(p) for t, _, p in sections).replace("**", "")
        io.open(args[1], "w", encoding="utf-8").write(plain)
        print("%d 節の字を %s へ書いた" % (len(sections), args[1])); return
    old = io.open(OUT, encoding="utf-8-sig").read() if os.path.exists(OUT) else None      # テキストで読むので改行は LF にそろう (作業コピーが CRLF でも一致を見られる)
    if args and args[0] == "--check":
        if old != body:
            print("Game2DTutorialText.cs が handbook と食い違う (python Tools/sync_handbook.py で作り直す)"); sys.exit(1)
        print("一致 (%d 節)" % len(sections)); return
    if old == body:
        print("変化なし (%d 節)" % len(sections)); return
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(body)
    print("%d 節を書いた: %s" % (len(sections), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
